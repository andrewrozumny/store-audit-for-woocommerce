<?php
/**
 * Export endpoint guard tests.
 *
 * @package StoreAudit
 */

declare(strict_types=1);

namespace StoreAudit\Tests\Unit\Admin;

use Brain\Monkey\Functions;
use StoreAudit\Admin\Exports;
use StoreAudit\Tests\Unit\TestCase;

/**
 * Tests for the capability and nonce gate.
 *
 * @covers \StoreAudit\Admin\Exports
 */
final class ExportsTest extends TestCase {

	/**
	 * Without the capability the request ends with 403 before the nonce is looked at.
	 */
	public function test_missing_capability_dies(): void {
		Functions\when( 'current_user_can' )->justReturn( false );
		Functions\expect( 'check_admin_referer' )->never();
		Functions\expect( 'wp_die' )->once()->with( \Mockery::type( 'string' ), '', array( 'response' => 403 ) )->andThrow( new \RuntimeException( 'died' ) );

		$this->expectException( \RuntimeException::class );
		( new Exports() )->authorize();
	}

	/**
	 * A failed nonce ends the request with 403.
	 */
	public function test_bad_nonce_dies(): void {
		Functions\when( 'current_user_can' )->justReturn( true );
		Functions\expect( 'check_admin_referer' )->once()->with( Exports::NONCE_ACTION )->andReturn( false );
		Functions\expect( 'wp_die' )->once()->with( \Mockery::type( 'string' ), '', array( 'response' => 403 ) )->andThrow( new \RuntimeException( 'died' ) );

		$this->expectException( \RuntimeException::class );
		( new Exports() )->authorize();
	}

	/**
	 * A valid request passes through.
	 */
	public function test_valid_request_passes(): void {
		Functions\when( 'current_user_can' )->justReturn( true );
		Functions\when( 'check_admin_referer' )->justReturn( 1 );
		Functions\expect( 'wp_die' )->never();

		( new Exports() )->authorize();
		$this->addToAssertionCount( 1 );
	}

	/**
	 * The printable document escapes dynamic values and carries the attribution link.
	 */
	public function test_print_document_escapes_and_attributes(): void {
		Functions\when( 'esc_url' )->returnArg();
		Functions\when( 'esc_attr' )->returnArg();
		Functions\when( 'get_option' )->justReturn( 'Y-m-d' );
		Functions\when( 'wp_date' )->justReturn( '2026-10-12' );
		Functions\when( 'wp_kses' )->returnArg();

		$report = array(
			'generated_at' => '2026-10-12T08:30:00Z',
			'site_url'     => 'https://shop.example.com',
			'score'        => array(
				'overall'  => 40,
				'sections' => array(),
			),
			'results'      => array(
				array(
					'section'  => 'security',
					'severity' => 'critical',
					'title'    => 'Title',
					'summary'  => 'Sum',
					'details'  => array( 'one' ),
					'fix_hint' => 'Fix it',
				),
			),
		);
		$html   = Exports::render_body( $report );

		$this->assertStringContainsString( 'Report generated by Store Audit for WooCommerce by Andrew Rozumny, ', $html );
		$this->assertStringContainsString( 'rel="noopener"', $html );
		$this->assertStringContainsString( 'Fix it', $html );
		$this->assertStringContainsString( 'is-poor', $html );
	}
}
