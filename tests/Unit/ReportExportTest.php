<?php
/**
 * Report export tests.
 *
 * @package StoreAudit
 */

declare(strict_types=1);

namespace StoreAudit\Tests\Unit;

use Brain\Monkey\Functions;
use StoreAudit\Report;

/**
 * Tests for the Markdown and JSON exports.
 *
 * @covers \StoreAudit\Report
 */
final class ReportExportTest extends TestCase {

	/**
	 * Stub the few WordPress functions the exports use.
	 */
	protected function set_up(): void {
		parent::set_up();
		Functions\when( 'wp_json_encode' )->alias(
			static fn( $data, int $options = 0 ) => json_encode( $data, $options ) // phpcs:ignore WordPress.WP.AlternativeFunctions.json_encode_json_encode
		);
		Functions\when( 'wp_parse_url' )->alias( 'parse_url' );
		Functions\when( 'sanitize_file_name' )->returnArg();
		Functions\when( 'esc_url' )->returnArg();
	}

	/**
	 * A report with a mix of severities in two sections.
	 *
	 * @return array<string,mixed>
	 */
	private function report(): array {
		$row = static fn( string $section, string $severity, string $title, string $hint = '', array $details = array() ): array => array(
			'id'          => $title,
			'section'     => $section,
			'title'       => $title,
			'severity'    => $severity,
			'summary'     => 'Summary of ' . $title,
			'details'     => $details,
			'explanation' => 'Why',
			'fix_hint'    => $hint,
			'duration_ms' => 1,
		);
		return array(
			'generated_at'   => '2026-10-12T08:30:00Z',
			'site_url'       => 'https://shop.example.com',
			'plugin_version' => '0.1.0',
			'wp_version'     => '7.1',
			'wc_version'     => '11.2',
			'score'          => array(
				'overall'  => 61,
				'sections' => array(
					'security'    => array(
						'label'  => 'Security',
						'score'  => 55,
						'counts' => array(
							'critical' => 1,
							'warning'  => 1,
							'info'     => 1,
							'ok'       => 2,
							'error'    => 0,
						),
					),
					'performance' => array(
						'label'  => 'Performance',
						'score'  => 98,
						'counts' => array(
							'critical' => 0,
							'warning'  => 0,
							'info'     => 1,
							'ok'       => 1,
							'error'    => 0,
						),
					),
				),
			),
			'results'        => array(
				$row( 'security', 'info', 'Info check' ),
				$row( 'security', 'ok', 'Fine check A' ),
				$row( 'security', 'warning', 'Warning check', 'Do the warning fix.', array( 'detail one', 'detail two' ) ),
				$row( 'security', 'critical', 'Critical check', 'Do the critical fix.' ),
				$row( 'security', 'ok', 'Fine check B' ),
				$row( 'security', 'error', 'Error check' ),
				$row( 'performance', 'info', 'Perf info' ),
				$row( 'performance', 'ok', 'Perf fine' ),
			),
		);
	}

	/**
	 * The attribution is exact.
	 */
	public function test_attribution_text(): void {
		$this->assertSame( 'Report generated by Store Audit for WooCommerce by Andrew Rozumny, helpmybiz.org', Report::attribution() );
		$this->assertStringContainsString( 'href="https://helpmybiz.org" target="_blank" rel="noopener"', Report::attribution_html() );
	}

	/**
	 * Markdown has the attribution, the score table and the sections.
	 */
	public function test_markdown_contains_attribution_and_sections(): void {
		$md = Report::to_markdown( $this->report() );

		$this->assertStringContainsString( 'Report generated by Store Audit for WooCommerce by Andrew Rozumny, [helpmybiz.org](https://helpmybiz.org)', $md );
		$this->assertStringContainsString( '# Store Audit report for https://shop.example.com', $md );
		$this->assertStringContainsString( '2026-10-12 08:30 UTC', $md );
		$this->assertStringContainsString( '**61 / 100**', $md );
		$this->assertStringContainsString( '| Security | 55 | 1 | 1 | 1 | 2 |', $md );
		$this->assertStringContainsString( '## Security (55 / 100)', $md );
		$this->assertStringContainsString( '## Performance (98 / 100)', $md );
		$this->assertStringContainsString( '**What to do:** Do the critical fix.', $md );
		$this->assertStringContainsString( "- detail one\n- detail two", $md );
		$this->assertSame( 1, preg_match( '/helpmybiz\.org\]\(https:\/\/helpmybiz\.org\)\n$/', $md ) );
	}

	/**
	 * Issues are listed critical, warning, error, info.
	 */
	public function test_markdown_severity_order(): void {
		$md        = Report::to_markdown( $this->report() );
		$positions = array(
			strpos( $md, '### Critical: Critical check' ),
			strpos( $md, '### Warning: Warning check' ),
			strpos( $md, '### Not checked: Error check' ),
			strpos( $md, '### Info: Info check' ),
		);

		$this->assertNotContains( false, $positions, 'every issue is listed' );
		$sorted = $positions;
		sort( $sorted );
		$this->assertSame( $sorted, $positions );
	}

	/**
	 * Passed checks are one list per section, not issue headings.
	 */
	public function test_markdown_collapses_passed_checks(): void {
		$md = Report::to_markdown( $this->report() );

		$this->assertStringNotContainsString( '### OK', $md );
		$this->assertSame( 2, substr_count( $md, '**Passed checks**' ) );
		$this->assertStringContainsString( "**Passed checks**\n\n- Fine check A\n- Fine check B\n", $md );
	}

	/**
	 * JSON is pretty-printed and carries generated_by.
	 */
	public function test_json_has_generated_by(): void {
		$json = Report::to_json( $this->report() );
		$data = json_decode( $json, true );

		$this->assertIsArray( $data );
		$this->assertSame( Report::attribution(), $data['generated_by'] );
		$this->assertSame( 61, $data['score']['overall'] );
		$this->assertStringContainsString( "\n    ", $json );
		$this->assertStringContainsString( 'https://shop.example.com', $json );
	}

	/**
	 * Download file name uses host and report date.
	 */
	public function test_filename(): void {
		$this->assertSame( 'store-audit-shop.example.com-2026-10-12.json', Report::filename( $this->report(), 'json' ) );
	}

	/**
	 * Text that comes from the site (plugin, theme and file names) cannot inject HTML, links or new
	 * Markdown blocks into a report that is pasted into a ticket or a chat.
	 */
	public function test_markdown_neutralises_site_text(): void {
		$report              = $this->report();
		$report['results'][] = array(
			'id'          => 'x',
			'section'     => 'security',
			'title'       => '<script>alert(1)</script>',
			'severity'    => 'critical',
			'summary'     => '"><img src=x onerror=alert(1)>',
			'details'     => array( "line one\n# Fake heading", '[click](javascript:alert(1))', "tab\tand\r\ncrlf" ),
			'explanation' => '',
			'fix_hint'    => '<b>bold</b>',
			'duration_ms' => 1,
		);

		$markdown = str_replace( Report::attribution_markdown(), '', Report::to_markdown( $report ) );

		$this->assertDoesNotMatchRegularExpression( '/(^|[^\\\\])<[a-zA-Z\/!]/', $markdown, 'an HTML tag is left in the Markdown' );
		$this->assertDoesNotMatchRegularExpression( '/(^|[^\\\\])\[[^\]]*\]\(/', $markdown, 'a Markdown link built from site text' );
		$this->assertStringNotContainsString( "\n# Fake heading", $markdown );
		$this->assertStringNotContainsString( "\r", $markdown );
		$this->assertStringContainsString( 'alert(1)', $markdown, 'the text itself must still be readable' );
	}

	/**
	 * Report with one sensitive row (account names in its details) and one plain row.
	 *
	 * @return array<string,mixed>
	 */
	private function sensitive_report(): array {
		$report              = $this->report();
		$report['results'][] = array(
			'id'          => 'security_admin_count',
			'section'     => 'security',
			'title'       => 'Administrator accounts',
			'severity'    => 'warning',
			'summary'     => '4 administrator accounts, more than the 3 a typical store needs.',
			'details'     => array( 'jdoe (email at example.com)', 'shopowner (email at example.com)' ),
			'explanation' => '',
			'fix_hint'    => '',
			'duration_ms' => 1,
			'sensitive'   => true,
		);
		return $report;
	}

	/**
	 * Markdown and JSON exports replace the details of sensitive checks with a count.
	 */
	public function test_exports_redact_sensitive_details(): void {
		$report = $this->sensitive_report();
		$md     = Report::to_markdown( $report );
		$json   = Report::to_json( $report );

		foreach ( array( $md, $json ) as $text ) {
			$this->assertStringNotContainsString( 'jdoe', $text );
			$this->assertStringNotContainsString( 'shopowner', $text );
			$this->assertStringContainsString( '2 items. Details are shown only on the Store Audit screen in wp-admin.', $text );
			$this->assertStringContainsString( '4 administrator accounts', $text, 'the summary stays' );
			$this->assertStringContainsString( 'detail one', $text, 'plain checks keep their details' );
		}
	}

	/**
	 * The command line asks for the full data.
	 */
	public function test_full_data_is_available_without_redaction(): void {
		$report = $this->sensitive_report();

		$this->assertStringContainsString( 'jdoe', Report::to_markdown( $report, false ) );
		$this->assertStringContainsString( 'jdoe', Report::to_json( $report, false ) );
	}

	/**
	 * The stored report keeps the flag and the full details; only the export copy is redacted.
	 */
	public function test_redaction_does_not_touch_the_stored_report(): void {
		$report   = $this->sensitive_report();
		$redacted = Report::redact_for_export( $report );

		$this->assertSame( $report, $this->sensitive_report() );
		$this->assertTrue( $redacted['results'][8]['sensitive'] );
		$this->assertCount( 1, $redacted['results'][8]['details'] );
	}

	/**
	 * An incomplete score is marked in the Markdown, and a section without a score says so.
	 */
	public function test_markdown_marks_incomplete_scores(): void {
		$report                        = $this->report();
		$report['score']['incomplete'] = true;
		$report['score']['checked']    = 10;
		$report['score']['total']      = 18;
		$report['score']['sections']['performance']['score'] = null;

		$md = Report::to_markdown( $report );

		$this->assertStringContainsString( '**61 / 100** (Incomplete: 10 of 18 checks ran)', $md );
		$this->assertStringContainsString( '| Performance | incomplete |', $md );
		$this->assertStringContainsString( '## Performance (incomplete)', $md );
	}

	/**
	 * The filter removes the attribution from exports only.
	 */
	public function test_attribution_filter_switches_exports_off(): void {
		\Brain\Monkey\Filters\expectApplied( 'store_audit_show_attribution' )->andReturn( false );

		$md   = Report::to_markdown( $this->report() );
		$json = Report::to_json( $this->report() );

		$this->assertStringNotContainsString( 'helpmybiz.org', $md );
		$this->assertStringNotContainsString( 'generated_by', $json );
		$this->assertStringContainsString( 'helpmybiz.org', Report::attribution_html(), 'the admin screen builds it regardless' );
	}
}
